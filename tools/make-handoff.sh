#!/usr/bin/env bash
# จัดชุดเอกสารส่งมอบกลับให้เจ้าของผลิตภัณฑ์
#
# วิธีใช้
#     bash tools/make-handoff.sh
#
# สร้างเอกสารใหม่ทุกฉบับก่อน แล้วรวบรวม PDF และ DOCX ไว้ในโฟลเดอร์ handoff
# พร้อมไฟล์ README.txt ที่บอกผู้รับว่าควรเริ่มอ่านที่ไหน

set -euo pipefail
cd "$(dirname "$0")/.."

echo "สร้างเอกสารทุกฉบับใหม่"
bash tools/build-docs.sh

rm -rf handoff
mkdir -p handoff

for F in docs/*.pdf docs/*.docx; do
  [ -f "$F" ] && cp "$F" handoff/
done

# ดึงเลขฉบับแก้ไขจากไฟล์ต้นฉบับ เพื่อใส่ในสารบัญของชุดส่งมอบ
rev() { grep -m1 'ฉบับแก้ไขครั้งที่ |' "$1.md" | sed 's/.*| \([0-9]*\) |.*/\1/'; }

cat > handoff/README.txt <<EOF
ชุดเอกสารการออกแบบระบบ  ส่งมอบกลับโดยนักวิเคราะห์ระบบ
แอปพลิเคชันสนับสนุนการปฏิบัติตามโปรแกรมการออกกำลังกายและแผนโภชนาการ
สร้างเมื่อ 1 สิงหาคม 2569

เริ่มอ่านที่  SRS-FIT-001  ข้อกำหนดความต้องการซอฟต์แวร์และการออกแบบระบบ
เอกสารดังกล่าวเป็นทางเข้าของชุด ระบุว่าเรื่องใดอยู่ในเอกสารฉบับใด
พร้อมตารางสอบทานย้อนกลับรวม ทะเบียนสมมติฐาน และทะเบียนประเด็นที่ต้องได้ข้อยุติ

รายการเอกสาร  ทุกฉบับมีทั้งรูปแบบ PDF และ DOCX

  SRS-FIT-001  rev $(rev SRS-FIT-001)  ข้อกำหนดความต้องการซอฟต์แวร์และการออกแบบระบบ  ทางเข้า
  ARC-FIT-001  rev $(rev ARC-FIT-001)  เอกสารสถาปัตยกรรมระบบ
  DM-FIT-001   rev $(rev DM-FIT-001)  เอกสารแบบจำลองข้อมูล
  DAY-FIT-001  rev $(rev DAY-FIT-001)  การออกแบบกลไกคำนวณวันของรอบโปรแกรม
  NAV-FIT-001  rev $(rev NAV-FIT-001)  ผังการไหลของหน้าจอ ฉบับเชิงตรรกะ  ส่งมอบบางส่วน
  TST-FIT-001  rev $(rev TST-FIT-001)  กรณีทดสอบจากเกณฑ์การยอมรับ
  EST-FIT-002  rev $(rev EST-FIT-002)  การประมาณปริมาณงานที่ปรับใหม่จากการออกแบบ
  CR-FIT-001   rev $(rev CR-FIT-001)  คำขอเปลี่ยนแปลงเอกสาร  ต้องพิจารณา

สิ่งที่ต้องดำเนินการก่อนอย่างอื่น

  1  พิจารณาคำขอเปลี่ยนแปลงใน CR-FIT-001
     ห้ารายการแรกใช้เวลารวมไม่ถึง 8 ชั่วโมง แต่ปิดรายการค้างได้ทั้งหมด
     และทำให้เกณฑ์การตรวจรับข้อ 6.4 และ 6.5 ของ TRN-FIT-001 ผ่านได้

  2  ตอบประเด็นที่ต้องได้ข้อยุติ 19 ข้อ ตามข้อ 15 ของ SRS-FIT-001
     ประเด็น Q17 ต้องได้คำตอบทันที เนื่องจากกระทบความถูกต้องของค่าประมาณทั้งฉบับ

  3  ยืนยันสมมติฐาน 20 ข้อ ตามข้อ 14 ของ SRS-FIT-001

ข้อควรทราบ

  เอกสารในชุดนี้เป็นเอกสารการออกแบบ  มิใช่ต้นฉบับของข้อกำหนด
  เมื่อขัดแย้งกับ PRD-FIT-001 หรือ REQ-FIT-001 ให้ถือตามเอกสารข้อกำหนด
  ตามข้อ 1.3 ของ SRS-FIT-001

  งานตามข้อ 4.4 ผังการไหลของหน้าจอ ส่งมอบได้เฉพาะส่วนที่ไม่ขึ้นกับแบบการออกแบบ
  ส่วนที่เหลือรอกลุ่มงานที่ 3.3 แล้วเสร็จ ณ หลักหมาย M2

  งานออกแบบทั้งหมดตั้งอยู่บนข้อสมมติฐานตามข้อ 5.3.2 ของ PRD-FIT-001
  ซึ่งระบุเองว่ายังมิใช่ข้อเท็จจริง  หากผลการสัมภาษณ์ผู้ใช้งานตามข้อ 5.3.3
  นำไปสู่การยุติโครงการ งานออกแบบทั้งหมดจะถูกระงับ
EOF

echo
echo "ชุดส่งมอบอยู่ในโฟลเดอร์ handoff"
ls -1 handoff | sed 's/^/  /'
